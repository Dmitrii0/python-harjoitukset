
eka_numero = int(input("Anna ensimmäinen kokonaisluku: "))
toka_numero = int(input("Anna toinen kokonaisluku: "))
kolmas_numero = int(input("Anna kolmas kokonaisluku: "))

summa = eka_numero + toka_numero + kolmas_numero
tulon = eka_numero * toka_numero * kolmas_numero
keskiarvo = summa / 3

print(f"Lukujen summa on: {summa}")
print(f"Lukujen tulo on: {tulon}")
print(f"Lukujen keskiarvo on: {keskiarvo}")
